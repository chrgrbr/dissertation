"""Derive shared assets for the 3 learned-representation icons of the shape-landscape figure.
Projects the real liver (abdomen_mrct, label 1) at the locked pose (elev=15, azim=-120) to:
  - liver_outline.tex : a TikZ smooth-cycle coordinate path of the 2D silhouette
  - thumb_field.png    : a soft-edged grayscale occupancy fill (the 'continuous field')
Run:  python sections/02_background/figures/gen_learned_assets.py
"""
import numpy as np, nibabel as nib
from scipy import ndimage as ndi
from skimage import measure
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt

SEG = "/Users/chris/Documents/CONVEA/MWE_demonstrator/data/cases/abdomen_mrct_0006/fixed_seg.nii.gz"
ELEV, AZIM = 15, -120
HERE = "sections/02_background/figures/shape_landscape/shared"

# --- load + crop liver ---
img = nib.as_closest_canonical(nib.load(SEG)); d = np.asarray(img.dataobj); liver = (d == 1)
xs, ys, zs = np.where(liver)
sl = tuple(slice(max(c.min() - 2, 0), c.max() + 3) for c in (xs, ys, zs))
b = liver[sl]

# --- camera basis at the locked pose (screen plane = e1,e2 orthogonal to view dir) ---
er, ar = np.radians(ELEV), np.radians(AZIM)
cam = np.array([np.cos(er) * np.cos(ar), np.cos(er) * np.sin(ar), np.sin(er)])  # to-camera
up = np.array([0.0, 0.0, 1.0])
e1 = np.cross(up, cam); e1 /= np.linalg.norm(e1)   # screen-x
e2 = np.cross(cam, e1)                             # screen-y (already unit)

# --- project voxels onto the screen plane and rasterise the footprint ---
P = np.argwhere(b).astype(float)
u = P @ e1; v = P @ e2
res = 220
ue = np.linspace(u.min() - 2, u.max() + 2, res + 1)
ve = np.linspace(v.min() - 2, v.max() + 2, res + 1)
H, _, _ = np.histogram2d(u, v, bins=[ue, ve])
mask = ndi.binary_fill_holes(ndi.binary_closing(H > 0, iterations=2))

# --- smooth occupancy field (soft edge) -> thumb_field.png (grayscale, transparent bg) ---
field = ndi.gaussian_filter(mask.astype(float), 3.0)
field /= field.max() + 1e-9
rgba = np.zeros(field.shape + (4,))
rgba[..., :3] = 0.30 + 0.55 * (1 - field)[..., None]   # dark interior -> light edge
rgba[..., 3] = np.clip(field * 1.4, 0, 1)              # alpha = occupancy
plt.imsave(f"{HERE}/thumb_field.png", np.ascontiguousarray(np.transpose(rgba, (1, 0, 2))[::-1]))

# --- outline contour -> normalised TikZ smooth-cycle path ---
cont = max(measure.find_contours(ndi.gaussian_filter(mask.astype(float), 1.0), 0.5), key=len)
cont = cont[:: max(1, len(cont) // 44)]                # ~44 points
uc = ue[0] + cont[:, 0] * (ue[1] - ue[0])
vc = ve[0] + cont[:, 1] * (ve[1] - ve[0])
uc -= uc.mean(); vc -= vc.mean()
s = 1.0 / (uc.max() - uc.min())                        # normalise width to 1.0
uc *= s; vc *= s
coords = "".join(f"({x:.3f},{y:.3f})" for x, y in zip(uc, vc))
with open(f"{HERE}/liver_outline.tex", "w") as f:
    f.write("% Auto-generated by gen_learned_assets.py — real liver silhouette at elev15/azim-120.\n")
    f.write("\\def\\liveroutline{plot[smooth cycle, tension=0.7] coordinates{" + coords + "}}\n")
print("wrote liver_outline.tex and thumb_field.png")
