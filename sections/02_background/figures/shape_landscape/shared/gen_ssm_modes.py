"""Derive three LOCALISED eigenmode-like deformations of the shared liver silhouette for the SSM
icon's RGB channel-split. Each mode bulges a different angular sector outward (radial Gaussian
displacement), so the three colour channels light up in different regions of the liver.
Writes shared/ssm_modes.tex with \\liverMone / \\liverMtwo / \\liverMthree (smooth-cycle paths).
Run from repo root:
python sections/02_background/figures/shape_landscape/shared/gen_ssm_modes.py
"""
import os, re
import numpy as np

SL = "sections/02_background/figures/shape_landscape"
txt = open(os.path.join(SL, "shared/liver_outline.tex")).read()
pts = np.array([[float(x), float(y)] for x, y in re.findall(r"\(([-\d.]+),([-\d.]+)\)", txt)])
cen = pts.mean(0)
rel = pts - cen
ang = np.arctan2(rel[:, 1], rel[:, 0])
rad = rel / (np.linalg.norm(rel, axis=1, keepdims=True) + 1e-9)   # outward radial dirs

# (anchor angle [deg], amplitude, angular sigma [deg]) -- spread over 3 distinct sectors
MODES = [(80, 0.13, 55), (205, 0.13, 55), (330, 0.13, 55)]


def wrap(a):
    return (a + np.pi) % (2 * np.pi) - np.pi


def deform(anchor_deg, amp, sig_deg):
    a0 = np.radians(anchor_deg); sig = np.radians(sig_deg)
    w = np.exp(-0.5 * (wrap(ang - a0) / sig) ** 2)
    return pts + (amp * w)[:, None] * rad


def path(p):
    coords = "".join(f"({x:.3f},{y:.3f})" for x, y in p)
    return "plot[smooth cycle, tension=0.7] coordinates{" + coords + "}"


names = ["\\liverMone", "\\liverMtwo", "\\liverMthree"]
with open(os.path.join(SL, "shared/ssm_modes.tex"), "w") as f:
    f.write("% Auto-generated by gen_ssm_modes.py -- localised eigenmode-like deformations.\n")
    for nm, (a, amp, s) in zip(names, MODES):
        f.write("\\def%s{%s}\n" % (nm, path(deform(a, amp, s))))
print("wrote shared/ssm_modes.tex")
