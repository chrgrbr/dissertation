"""Emit a smoothly warped deformation grid as a TikZ macro for the deformation-field icon.

Produces shared/deform_grid.tex defining \\deformgrid: an N x N grid over [-0.5,0.5]^2
displaced by a gentle (diffeomorphic) bump so the lines bow without crossing -- the
canonical registration "warped grid" glyph. Coordinates are normalised to width 1.0 so
the icon can scale it like the liver outline.

Run:  python sections/02_background/figures/shape_landscape/shared/gen_deform_grid.py
"""
import numpy as np

HERE = "sections/02_background/figures/shape_landscape/shared"
N = 5            # grid lines per direction
S = 26           # samples per line (smoothness)
HALF = 0.5

def warp(x, y):
    # gentle off-centre bulge + mild shear; amplitudes chosen to stay diffeomorphic
    cx, cy = 0.10, -0.05
    g = np.exp(-((x - cx) ** 2 + (y - cy) ** 2) / (2 * 0.11))
    dx = 0.55 * g * (x - cx) + 0.10 * y
    dy = 0.55 * g * (y - cy) - 0.06 * x
    return x + dx, y + dy

lines = np.linspace(-HALF, HALF, N)
t = np.linspace(-HALF, HALF, S)

paths = []
for xc in lines:                        # vertical lines (vary y)
    xs, ys = warp(np.full_like(t, xc), t)
    paths.append(list(zip(xs, ys)))
for yc in lines:                        # horizontal lines (vary x)
    xs, ys = warp(t, np.full_like(t, yc))
    paths.append(list(zip(xs, ys)))

# --- apply the SAME warp to the liver outline -> phi(S_0), so the result is
#     literally the template warped (not a look-alike mode shape) ---
import re
with open(f"{HERE}/liver_outline.tex") as f:
    txt = f.read()
pts = re.findall(r"\(([-0-9.]+),([-0-9.]+)\)", txt)
lx = np.array([float(a) for a, _ in pts])
ly = np.array([float(b) for _, b in pts])
wlx, wly = warp(lx, ly)
# renormalise warped liver to width 1.0, centred (same convention as liver_outline)
wlx -= wlx.mean(); wly -= wly.mean()
ls = 1.0 / (wlx.max() - wlx.min())
wlx *= ls; wly *= ls
warped_liver = "".join(f"({x:.3f},{y:.3f})" for x, y in zip(wlx, wly))

# normalise overall width to 1.0, centre on origin
allpts = np.array([p for path in paths for p in path])
w = allpts[:, 0].max() - allpts[:, 0].min()
sc = 1.0 / w
cx = (allpts[:, 0].max() + allpts[:, 0].min()) / 2
cy = (allpts[:, 1].max() + allpts[:, 1].min()) / 2

def emit(path):
    pts = "".join(f"({(x - cx) * sc:.3f},{(y - cy) * sc:.3f})" for x, y in path)
    return "  \\draw[liveredge!65, line width=0.30pt] plot[smooth,tension=0.75] coordinates{" + pts + "};"

with open(f"{HERE}/deform_grid.tex", "w") as f:
    f.write("% Auto-generated by gen_deform_grid.py -- warped deformation grid (width 1.0).\n")
    f.write("\\newcommand{\\deformgrid}{%\n")
    f.write("\n".join(emit(p) for p in paths))
    f.write("\n}\n")
    f.write("% phi(S_0): the liver outline under the SAME warp, normalised to width 1.0.\n")
    f.write("\\def\\liverwarped{plot[smooth cycle, tension=0.7] coordinates{"
            + warped_liver + "}}\n")
print(f"wrote {HERE}/deform_grid.tex ({len(paths)} lines + warped liver)")
